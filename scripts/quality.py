import io
import json
import re
import shutil
import subprocess
import sys
import tokenize
from pathlib import Path, PurePosixPath

from change_spec import OWNER_ROOTS, SPEC_PATH, covers, read_spec

ROOT = Path(__file__).resolve().parents[1]
PRIVATE = {".local", ".agents", ".codex", ".superpowers"}
RUNTIME = {"data", "secrets", "runs", "backups", "logs"}
TEXT_SUFFIXES = {".py", ".md", ".json", ".yaml", ".yml", ".toml", ".example"}
COMMENT_CHECK_SUFFIXES = {".py", ".yaml", ".yml"}


def git(*args, cwd=ROOT):
    return subprocess.check_output(["git", *args], cwd=cwd)


def forbidden_path(name):
    path = PurePosixPath(name.lower())
    return (
        bool(set(path.parts) & (PRIVATE | RUNTIME))
        or (path.name.startswith(".env") and path.name != ".env.example")
        or path.suffix in {".pem", ".key", ".p12", ".pfx", ".db"}
        or ".sqlite" in path.name
        or path.name.endswith((".db-wal", ".db-shm"))
    )


def check_comments(name, content):
    suffix = PurePosixPath(name).suffix
    if suffix == ".py":
        for token in tokenize.tokenize(io.BytesIO(content).readline):
            line, column = token.start
            is_shebang = (line, column) == (1, 0) and token.string.startswith("#!")
            if token.type == tokenize.COMMENT and not is_shebang:
                raise ValueError(f"{name}:{line}: remove source comment")
    elif suffix in {".yaml", ".yml"}:
        import yaml

        source = content.decode("utf-8")
        previous_end = 0
        for token in yaml.scan(source):
            comment = source.find("#", previous_end, token.start_mark.index)
            if comment != -1:
                line = source.count("\n", 0, comment) + 1
                raise ValueError(f"{name}:{line}: remove source comment")
            previous_end = max(previous_end, token.end_mark.index)


def check_content(name, content):
    if forbidden_path(name):
        raise ValueError(f"Forbidden public path: {name}")
    if PurePosixPath(name).suffix not in TEXT_SUFFIXES and name != ".gitignore":
        return
    text = content.decode("utf-8")
    if re.search(
        r"(?im)^\s*(?:#+|//)\s*(?:generated by (?:chatgpt|codex)|as an ai language model|마스터[,: ])",
        text,
    ) or re.search(r"\]\((?:\./)?(?:\.local|\.agents|\.superpowers)/", text):
        raise ValueError(f"Private workflow reference in public content: {name}")
    if text and not text.endswith("\n"):
        raise ValueError(f"Missing final newline: {name}")
    if any(line.rstrip() != line for line in text.splitlines()):
        raise ValueError(f"Trailing whitespace: {name}")
    check_comments(name, content)
    if name.endswith(".json"):
        json.loads(text)
    if name.endswith((".yml", ".yaml")):
        import yaml

        list(yaml.safe_load_all(text))


def require_gitleaks():
    executable = shutil.which("gitleaks")
    local = ROOT / ".local/bin/gitleaks"
    if executable is None and local.is_file():
        executable = str(local)
    if executable is None:
        raise RuntimeError("Gitleaks 8.24.2 is required; see docs/development-quality.md")
    version = subprocess.check_output([executable, "version"], text=True).strip().lstrip("v")
    if version != "8.24.2":
        raise RuntimeError("Expected Gitleaks 8.24.2")
    return executable


def scan_content(payload):
    executable = require_gitleaks()
    subprocess.run(
        [executable, "stdin", "--redact", "--no-banner"], input=payload, cwd=ROOT, check=True
    )


def staged():
    git("rev-parse", "--show-toplevel")
    names = git("diff", "--cached", "--name-only", "--diff-filter=ACMR", "-z").split(b"\0")
    blobs = []
    for raw in filter(None, names):
        name = raw.decode()
        if forbidden_path(name):
            raise ValueError(f"Forbidden staged path: {name}")
        blobs.append(git("show", f":{name}"))
    scan_content(b"\n".join(blobs))


def history_range(local_sha, remote_sha):
    if set(remote_sha) == {"0"}:
        return local_sha
    return f"{remote_sha}..{local_sha}"


def audit_revision(revision, log_range):
    names = git("ls-tree", "-r", "--name-only", "-z", revision).split(b"\0")
    for raw in filter(None, names):
        if forbidden_path(raw.decode()):
            raise ValueError(f"Forbidden committed path: {raw.decode()}")
    names = git("log", "--format=", "--name-only", "-z", log_range).split(b"\0")
    for raw in filter(None, names):
        name = raw.decode().strip("\n")
        if name and forbidden_path(name):
            raise ValueError(f"Forbidden historical path: {name}")
    executable = require_gitleaks()
    subprocess.run(
        [executable, "git", "--redact", "--no-banner", f"--log-opts={log_range}", "."],
        cwd=ROOT,
        check=True,
    )


def changed_paths(base, revision, *, diff_filter=""):
    args = ["diff", "--no-renames", "--name-only", "-z"]
    if diff_filter:
        args.append(f"--diff-filter={diff_filter}")
    return {name.decode() for name in git(*args, base, revision, "--").split(b"\0") if name}


def check_spec_change(base, revision):
    ancestor = git("merge-base", base, revision).decode().strip()
    changed = changed_paths(ancestor, revision) & changed_paths(base, revision)
    present = changed_paths(ancestor, revision, diff_filter="ACMRT")
    scopes = [
        read_spec(path, git("show", f"{revision}:{path}"))["scope"]
        for path in sorted(changed & present)
        if SPEC_PATH.fullmatch(path)
    ]
    uncovered = [
        name
        for name in sorted(changed)
        if name.startswith(tuple(OWNER_ROOTS.values()))
        and not any(covers(scope, name) for scope in scopes)
    ]
    if uncovered:
        raise ValueError("Missing changed spec scope for: " + ", ".join(uncovered))


def worker_start(path, owner):
    if not SPEC_PATH.fullmatch(path):
        raise ValueError("Use specs/<change-id>.json")
    record = read_spec(path, (ROOT / path).read_bytes())
    if owner not in record["scope"]:
        raise ValueError(f"{path}: no paths assigned to {owner}")
    print(f"Ready: {path} ({owner})")
    print(
        json.dumps(
            {**record, "scope": {owner: record["scope"][owner]}}, ensure_ascii=False, indent=2
        )
    )


def push():
    updates = [line.split() for line in sys.stdin if line.strip()]
    if not updates or any(len(row) != 4 for row in updates):
        raise RuntimeError("Expected Git pre-push ref updates on stdin")
    head = git("rev-parse", "HEAD").decode().strip()
    active = [row for row in updates if set(row[1]) != {"0"}]
    for _, local_sha, _, remote_sha in active:
        commit = git("rev-parse", f"{local_sha}^{{commit}}").decode().strip()
        if commit != head:
            raise RuntimeError("Check out the pushed commit before running project tests")
        audit_revision(commit, history_range(commit, remote_sha))
    if active:
        if git("status", "--porcelain", "--untracked-files=no").strip():
            raise RuntimeError("Tracked working tree must match the pushed commit")
        if any(remote_ref.startswith("refs/heads/") for _, _, remote_ref, _ in active):
            check_spec_change("origin/main", head)
        check()


def check():
    names = git("ls-files", "--cached", "--others", "--exclude-standard", "-z").split(b"\0")
    for raw in filter(None, names):
        name = raw.decode()
        path = ROOT / name
        if path.suffix in COMMENT_CHECK_SUFFIXES and path.is_file():
            check_comments(name, path.read_bytes())
    for command in (
        ["uv", "run", "--frozen", "ruff", "check", "."],
        ["uv", "run", "--frozen", "ruff", "format", "--check", "."],
        [sys.executable, "scripts/validate.py"],
        [
            "uv",
            "run",
            "--frozen",
            "lint-imports",
            "--no-cache",
            "--config",
            "services/research/pyproject.toml",
        ],
        ["uv", "run", "--frozen", "pytest"],
    ):
        subprocess.run(command, cwd=ROOT, check=True)


def main():
    mode = sys.argv[1] if len(sys.argv) > 1 else "check"
    if mode == "staged":
        staged()
    elif mode == "push":
        push()
    elif mode == "audit":
        names = git("ls-files", "--cached", "-z").split(b"\0")
        for raw in filter(None, names):
            name = raw.decode()
            check_content(name, git("show", f":{name}"))
        audit_revision("HEAD", "--all")
    elif mode == "files":
        for name in sys.argv[2:]:
            path = ROOT / name
            if path.is_file():
                check_content(name, path.read_bytes())
    elif mode == "spec-change" and len(sys.argv) == 4:
        check_spec_change(sys.argv[2], sys.argv[3])
    elif mode == "worker-start" and len(sys.argv) == 4:
        worker_start(sys.argv[2], sys.argv[3])
    elif mode == "check":
        check()
    else:
        raise ValueError(
            "Expected check, staged, files, push, audit, spec-change BASE REVISION, "
            "or worker-start SPEC OWNER"
        )


if __name__ == "__main__":
    try:
        main()
    except (
        ValueError,
        OSError,
        subprocess.CalledProcessError,
        RuntimeError,
        tokenize.TokenError,
    ) as error:
        print(f"Quality check failed: {error}", file=sys.stderr)
        sys.exit(1)
